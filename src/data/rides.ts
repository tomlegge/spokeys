/**
 * The single source of truth for rides.
 *
 * To add a new ride:
 *   1. Drop your GPX or KML file(s) into `public/rides/`
 *   2. Drop any photos into `public/photos/<slug>/`
 *   3. (Optional) Write a blog post at `public/blogs/<slug>.md` and set
 *      `hasBlog: true` on the ride below
 *   4. Append a new entry to the array below
 *   5. Commit & push — GitHub Actions deploys it
 *
 * `slug` becomes the URL: /rides/<slug>
 *
 * Route files — pick ONE of these:
 *   `file`  — a single GPX/KML path (use this for normal rides).
 *   `files` — an array of GPX/KML paths for rides that span multiple, possibly
 *             disconnected tracks (e.g. a tour where you took a train between
 *             two days, or where you only have separate tracks per stage).
 *             Each file is drawn as its own polyline on the map (no fake line
 *             joining them), and the gap between segments does NOT count
 *             toward total distance / elevation / duration.
 *   Either is optional — omit both (or leave them commented out) if you don't
 *   have a track yet. Rides without a track still show in the list.
 *
 *   Transfers (ferries, trains, lifts — anything you didn't pedal):
 *   Inside `files`, you can swap any plain string for an object like
 *     { url: `${base}rides/Ferry.gpx`, transfer: true }
 *   That segment will be drawn as a DOTTED line on the map and will NOT count
 *   toward distance, elevation, duration, or the rider leaderboard. Plain
 *   string entries continue to behave as normal cycled segments.
 *
 * `blogUrl` (optional): one or more external blog posts about the ride.
 * Three forms are accepted:
 *   - a plain string URL — renders a single "Read the blog →" button
 *       blogUrl: "https://example.com/post"
 *   - an object with an optional name — renders a button with that name
 *       blogUrl: { url: "https://example.com/post", name: "Anita's blog" }
 *   - an array mixing either form — renders one button per entry, side by
 *     side (use this when several people blogged about the same ride)
 *       blogUrl: [
 *         { url: "https://example.com/anita", name: "Anita's blog" },
 *         { url: "https://example.com/tom",   name: "Tom's recap" },
 *       ]
 * Each button opens in a new tab. Leave the field off entirely (or commented
 * out) if there's no external post.
 *
 * `hasBlog` (optional): set to `true` when you also want to host a blog post
 * directly on this site. Drop a markdown file at `public/blogs/<slug>.md`
 * and the ride page will add an extra button linking to `/rides/<slug>/blog`
 * alongside any external links. Internal and external links coexist now —
 * both render as separate pills.
 *
 * `photoTags` (optional): record who appears in each photo, keyed by the
 * photo's filename (NOT its full URL). Example:
 *   photoTags: {
 *     "flickr_4717959752.jpg": ["Anita", "Darren"],
 *     "flickr_4717958966.jpg": ["Anita"],
 *   }
 * Tag names should match the rider's display name (e.g. "Anita", not
 * "Anita (BBQ only)"). Untagged photos still show — they just don't match
 * any rider filter on the Photos page. Hovering / opening a tagged photo
 * surfaces the list of people in the lightbox.
 *
 * Use import.meta.env.BASE_URL so paths work in dev (`/`) AND on
 * GitHub Pages (`/spokeys/`). Don't hardcode the prefix.
 */

const base = import.meta.env.BASE_URL;

/**
 * One entry in a ride's `files` list. Plain strings are treated as a normal
 * cycled segment. Objects let you flag a segment as a `transfer` — a
 * non-cycled bit like a ferry crossing or a train hop — which is drawn as a
 * dotted line and excluded from all distance / elevation / duration stats.
 */
export type RouteFile = {
  url: string;
  transfer?: boolean;
};

/**
 * One external blog post about a ride. `name` is shown on the button (e.g.
 * "Anita's blog"); leave it off for a single link and the button falls back
 * to "Read the blog →".
 */
export type BlogLink = {
  url: string;
  name?: string;
};

/** What `Ride.blogUrl` is allowed to be. See the file header for examples. */
export type BlogUrlField =
  | string
  | BlogLink
  | (string | BlogLink)[];

export type Ride = {
  slug: string;
  title: string;
  date: string; // ISO date "YYYY-MM-DD"
  file?: string; // single GPX/KML path under public/. Use for normal rides.
  files?: (string | RouteFile)[]; // multiple GPX/KML paths under public/. Use when a ride spans disconnected tracks. Use the object form to mark a file as a non-cycled transfer (ferry, train, etc.).
  riders: string[];
  description: string;
  photos?: string[]; // paths under public/, relative to BASE_URL
  /**
   * Optional map of photo-filename → list of riders in the photo. Filename
   * is just the basename (e.g. "flickr_4717959752.jpg"), NOT the full path
   * — that way you only need to type it once even if you ever move the
   * photos folder. Used to drive the rider filter on /photos and to caption
   * the lightbox. See file header for an example.
   */
  photoTags?: Record<string, string[]>;
  color?: string; // route line color on the overview map
  blogUrl?: BlogUrlField; // one or more external blog posts. See file header for the three accepted shapes.
  hasBlog?: boolean; // set true if a markdown post exists at public/blogs/<slug>.md
};

/**
 * Resolve a ride's route files into a normalised array of `RouteFile`
 * objects. Plain string entries are wrapped into objects with `transfer:
 * false`. Returns an empty array when no track has been uploaded.
 */
export function rideFiles(ride: Ride): RouteFile[] {
  const normalise = (entry: string | RouteFile): RouteFile =>
    typeof entry === "string" ? { url: entry } : entry;
  if (ride.files && ride.files.length > 0) return ride.files.map(normalise);
  if (ride.file) return [{ url: ride.file }];
  return [];
}

/**
 * Resolve a ride's `blogUrl` field into a normalised array of `BlogLink`s,
 * regardless of which of the three accepted shapes it was written in. Empty
 * array if the field is unset.
 */
export function rideBlogLinks(ride: Ride): BlogLink[] {
  const raw = ride.blogUrl;
  if (raw == null) return [];
  const normaliseOne = (entry: string | BlogLink): BlogLink =>
    typeof entry === "string" ? { url: entry } : entry;
  if (Array.isArray(raw)) return raw.map(normaliseOne);
  return [normaliseOne(raw)];
}

/**
 * Extract just the filename from a photo URL. Tag lookups are keyed by
 * basename so the user only needs to type the filename once in `photoTags`,
 * not the full `${base}photos/<slug>/...` path that lives in `photos`.
 */
export function photoBasename(url: string): string {
  const noQuery = url.split("?")[0].split("#")[0];
  const idx = noQuery.lastIndexOf("/");
  return idx >= 0 ? noQuery.slice(idx + 1) : noQuery;
}

/**
 * Names of riders tagged in a given photo on a given ride, or `[]` if the
 * photo is untagged. Lookup is by filename (see `photoBasename`).
 */
export function peopleInPhoto(ride: Ride, photoUrl: string): string[] {
  const tags = ride.photoTags;
  if (!tags) return [];
  return tags[photoBasename(photoUrl)] ?? [];
}

