import { useEffect, useState } from "react";
import { RIDES, rideFiles, type Ride, type RouteFile } from "../data/rides";
import { combineStats, loadRoutes, type RouteStats } from "./routeLoader";

/**
 * Lightweight per-ride route data for the overview pages (Map, Stats): ride
 * totals, bounds, and a simplified line per segment. The ride detail page
 * still loads the full GPX via loadRoutes() for the elevation profile and
 * full-resolution track.
 */
export type RouteSummary = {
  stats: RouteStats;
  bounds: [[number, number], [number, number]]; // [[south, west], [north, east]]
  segments: { points: [number, number][]; transfer: boolean }[];
};

export type LoadedRide = {
  ride: Ride;
  status: "loading" | "ready" | "error" | "no-route";
  data?: RouteSummary;
  error?: string;
};

type FileSummary = {
  stats: RouteStats;
  bounds: [[number, number], [number, number]];
  line: [number, number][];
};

const BASE = import.meta.env.BASE_URL;

/**
 * route-summaries.json is generated by scripts/build-route-summaries.ts
 * before every dev/build run. Fetched once per page load and shared by every
 * page; resolves to an empty map if it's missing, so everything falls back
 * to loading GPX files directly.
 */
let summariesPromise: Promise<Record<string, FileSummary>> | null = null;
function loadFileSummaries(): Promise<Record<string, FileSummary>> {
  summariesPromise ??= fetch(`${BASE}route-summaries.json`)
    .then((res) => (res.ok ? res.json() : { files: {} }))
    .then((json) => (json?.files ?? {}) as Record<string, FileSummary>)
    .catch(() => ({}));
  return summariesPromise;
}

/** "/rides/foo.gpx" → "rides/foo.gpx" (the key used in the summary file). */
function summaryKey(url: string): string {
  return url.startsWith(BASE) ? url.slice(BASE.length) : url.replace(/^\//, "");
}

function unionBounds(
  all: [[number, number], [number, number]][],
): [[number, number], [number, number]] {
  let s = Infinity, w = Infinity, n = -Infinity, e = -Infinity;
  for (const [[bs, bw], [bn, be]] of all) {
    s = Math.min(s, bs); w = Math.min(w, bw);
    n = Math.max(n, bn); e = Math.max(e, be);
  }
  return [[s, w], [n, e]];
}

async function loadRideSummary(
  files: RouteFile[],
  summaries: Record<string, FileSummary>,
): Promise<RouteSummary> {
  const found = files.map((f) => summaries[summaryKey(f.url)]);
  if (found.every(Boolean)) {
    return {
      stats: combineStats(
        files.map((f, i) => ({ transfer: !!f.transfer, stats: found[i].stats })),
      ),
      bounds: unionBounds(found.map((s) => s.bounds)),
      segments: files.map((f, i) => ({
        points: found[i].line,
        transfer: !!f.transfer,
      })),
    };
  }
  // Not in the summary (new file in dev, or the summary failed to build):
  // load the full GPX/KML instead.
  const data = await loadRoutes(files);
  return {
    stats: data.stats,
    bounds: data.bounds,
    segments: data.segments.map((seg) => ({
      points: seg.points.map((p) => [p.lat, p.lng] as [number, number]),
      transfer: !!seg.transfer,
    })),
  };
}

let ridesPromise: Promise<LoadedRide[]> | null = null;
function loadAllRides(): Promise<LoadedRide[]> {
  ridesPromise ??= loadFileSummaries().then((summaries) =>
    Promise.all(
      RIDES.map(async (ride): Promise<LoadedRide> => {
        const files = rideFiles(ride);
        if (files.length === 0) return { ride, status: "no-route" };
        try {
          return { ride, status: "ready", data: await loadRideSummary(files, summaries) };
        } catch (err) {
          return {
            ride,
            status: "error",
            error: err instanceof Error ? err.message : String(err),
          };
        }
      }),
    ),
  );
  return ridesPromise;
}

let cached: LoadedRide[] | null = null;

/**
 * Route summaries for every ride, for the overview pages. Loaded once and
 * cached for the rest of the visit, so moving between Map and Stats is
 * instant. Rides without any route file get status "no-route".
 */
export function useRideRoutes(): LoadedRide[] {
  const [state, setState] = useState<LoadedRide[]>(
    () =>
      cached ??
      RIDES.map((r) => ({
        ride: r,
        status: rideFiles(r).length > 0 ? "loading" : "no-route",
      })),
  );

  useEffect(() => {
    if (cached) return;
    let cancelled = false;
    loadAllRides().then((results) => {
      cached = results;
      if (!cancelled) setState(results);
    });
    return () => {
      cancelled = true;
    };
  }, []);

  return state;
}
